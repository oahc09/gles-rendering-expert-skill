#!/usr/bin/env python3
"""Refresh human-readable rule inventory and exact line references from catalog."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
path = ROOT/'benchmarks/rules/catalog.json'
catalog = json.loads(path.read_text())
lines = ['# Scoped rule inventory', '', 'Generated by `python tools/build_rule_inventory.py`. These are 30 scoped machine', 'rules, not an exhaustive parser of every inherited vendor recommendation.', 'See baseline-files.txt for the preserved inherited rule/card inventory.', '']
for rule in catalog:
    if rule['source_file'] != 'benchmarks/rules/inventory.md':
        rule['related_files'] = [rule['source_file']]
    rule['source_file'] = 'benchmarks/rules/inventory.md'
    rule['source_line'] = len(lines)+1
    rule['source_anchor'] = rule['rule_id']
    lines.extend([f"## {rule['rule_id']} — {rule['title']}", '', f"- Level: {rule['normative_level']}; severity: {rule['severity']}", f"- Minimum scoped GLES/GLSL: {rule['gles_min_version']} / {rule['glsl_version']}", f"- Source: {rule['normative_source']}", f"- Inputs: {', '.join(rule['fields'])}", f"- Positive: {', '.join(rule['positive_tests'])}; negative: {', '.join(rule['negative_tests'])}", f"- Fallback: {rule['fallback']}", f"- Conditions: {rule['vendor_conditions']}", f"- Related inherited guidance: {', '.join(rule['related_files'])}", ''])
(ROOT/'benchmarks/rules/inventory.md').write_text('\n'.join(lines)+'\n')
path.write_text(json.dumps(catalog,indent=2)+'\n')
